#!/usr/bin/env node
// Bridges Claude Code's stdio MCP client to `codex app-server --stdio`.
// `codex mcp-server` (the old direct MCP server) was removed upstream; app-server
// speaks a different, non-MCP JSON-RPC protocol (thread/turn/item based, no
// `jsonrpc` field on the wire). This process translates between the two,
// re-exposing the same `codex` / `codex-reply` tool surface the old
// `mcp-server` used to provide.

import { spawn } from "node:child_process";
import readline from "node:readline";

const CODEX_TOOL = {
  name: "codex",
  title: "Codex",
  description: "Run a Codex session. Accepts configuration parameters matching the Codex Config struct.",
  inputSchema: {
    additionalProperties: false,
    properties: {
      "approval-policy": {
        description: "Approval policy for shell commands generated by the model: `on-request`, `never`.",
        type: "string",
        enum: ["on-request", "never"]
      },
      "base-instructions": {
        description: "The set of instructions to use instead of the default ones.",
        type: "string"
      },
      "compact-prompt": {
        description: "Prompt used when compacting the conversation.",
        type: "string"
      },
      config: {
        description: "Individual config settings that will override what is in CODEX_HOME/config.toml.",
        type: "object",
        additionalProperties: true
      },
      cwd: {
        description: "Working directory for the session. If relative, it is resolved against the server process's current working directory.",
        type: "string"
      },
      "developer-instructions": {
        description: "Developer instructions that should be injected as a developer role message.",
        type: "string"
      },
      model: {
        description: "Optional override for the model name (e.g. 'gpt-5.2', 'gpt-5.2-codex').",
        type: "string"
      },
      prompt: {
        description: "The *initial user prompt* to start the Codex conversation.",
        type: "string"
      },
      sandbox: {
        description: "Sandbox mode: `read-only`, `workspace-write`, or `danger-full-access`.",
        type: "string",
        enum: ["read-only", "workspace-write", "danger-full-access"]
      }
    },
    required: ["prompt"],
    type: "object"
  },
  outputSchema: {
    type: "object",
    properties: { threadId: { type: "string" }, content: { type: "string" } },
    required: ["threadId", "content"]
  }
};

const CODEX_REPLY_TOOL = {
  name: "codex-reply",
  title: "Codex Reply",
  description: "Continue a Codex conversation by providing the thread id and prompt.",
  inputSchema: {
    properties: {
      conversationId: { description: "DEPRECATED: use threadId instead.", type: "string" },
      prompt: { description: "The *next user prompt* to continue the Codex conversation.", type: "string" },
      threadId: {
        description: "The thread id for this Codex session. This field is required, but we keep it optional here for backward compatibility for clients that still use conversationId.",
        type: "string"
      }
    },
    required: ["prompt"],
    type: "object"
  },
  outputSchema: {
    type: "object",
    properties: { threadId: { type: "string" }, content: { type: "string" } },
    required: ["threadId", "content"]
  }
};

// --- Downstream: JSON-RPC client talking to `codex app-server --stdio` ---
// app-server omits the `jsonrpc` field on the wire; MCP (upstream) requires it.
// The two id spaces are independent: this class mints its own ids for requests
// to codex, unrelated to whatever ids Claude Code sends us upstream.
class AppServerClient {
  constructor() {
    this.proc = spawn("codex", ["app-server", "--stdio"], { stdio: ["pipe", "pipe", "pipe"] });
    this.nextId = 1;
    this.pending = new Map();
    this.notificationHandler = null;
    this.onExit = null;
    this.closed = false;
    this.exitError = null;

    this.proc.on("error", (err) => {
      this._handleExit(new Error(`failed to start codex app-server: ${err.message}`));
    });
    this.proc.on("exit", (code, signal) => {
      if (!this.closed) {
        this._handleExit(new Error(`codex app-server exited unexpectedly (code=${code} signal=${signal})`));
      }
    });
    this.proc.stderr.on("data", (chunk) => {
      process.stderr.write(chunk);
    });

    const rl = readline.createInterface({ input: this.proc.stdout, crlfDelay: Infinity });
    rl.on("line", (line) => this._handleLine(line));

    this.ready = this._handshake();
  }

  async _handshake() {
    await this.request("initialize", {
      clientInfo: { name: "claude-code-codex-bridge", title: "Codex MCP Bridge", version: "1.0.0" }
    });
    this.notify("initialized", {});
  }

  _handleLine(line) {
    if (!line.trim()) return;
    let msg;
    try {
      msg = JSON.parse(line);
    } catch {
      process.stderr.write(`[codex-mcp-bridge] unparseable line from codex app-server: ${line}\n`);
      return;
    }

    if (msg.id !== undefined && msg.method) {
      // Server-initiated request (e.g. an approval prompt). We have no way to
      // answer these, so reject immediately rather than hang the turn.
      this._write({ id: msg.id, error: { code: -32601, message: `Unsupported server request: ${msg.method}` } });
      return;
    }

    if (msg.id !== undefined) {
      const pending = this.pending.get(msg.id);
      if (!pending) return;
      this.pending.delete(msg.id);
      if (msg.error) {
        const err = new Error(msg.error.message || "codex app-server error");
        err.rpcError = msg.error;
        pending.reject(err);
      } else {
        pending.resolve(msg.result ?? {});
      }
      return;
    }

    if (msg.method) {
      this.notificationHandler?.(msg);
    }
  }

  _write(obj) {
    if (this.proc.stdin.destroyed) return;
    this.proc.stdin.write(JSON.stringify(obj) + "\n");
  }

  request(method, params) {
    if (this.exitError) return Promise.reject(this.exitError);
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this._write({ id, method, params });
    });
  }

  notify(method, params) {
    if (this.exitError) return;
    this._write({ method, params });
  }

  _handleExit(err) {
    if (this.closed && this.exitError) return;
    this.closed = true;
    this.exitError = err;
    for (const { reject } of this.pending.values()) reject(err);
    this.pending.clear();
    this.onExit?.(err);
  }

  close() {
    this.closed = true;
    try {
      this.proc.stdin.end();
    } catch {}
    setTimeout(() => {
      try {
        this.proc.kill("SIGTERM");
      } catch {}
    }, 50).unref?.();
  }
}

const appServer = new AppServerClient();
appServer.ready.catch((err) => {
  process.stderr.write(`[codex-mcp-bridge] codex app-server handshake failed: ${err.message}\n`);
});

// Per-thread turn tracking. Only one turn runs at a time per threadId for our
// two tools, so routing notifications by threadId alone (no turnId tracking)
// is sufficient and avoids the notification-buffering complexity a more
// general client would need.
const knownThreads = new Set();
const activeTurns = new Map(); // threadId -> { completion, resolve, reject, settled, lastAgentMessage, finalAnswer, error }

appServer.notificationHandler = (msg) => {
  const threadId = msg.params?.threadId;
  if (!threadId) return;
  const state = activeTurns.get(threadId);
  if (!state) return;

  switch (msg.method) {
    case "item/completed": {
      const item = msg.params.item;
      if (item?.type === "agentMessage" && item.text) {
        state.lastAgentMessage = item.text;
        if (item.phase === "final_answer") state.finalAnswer = item.text;
      }
      break;
    }
    case "error":
      state.error = msg.params.error;
      break;
    case "turn/completed":
      settleTurn(state, msg.params.turn);
      break;
    default:
      break;
  }
};

appServer.onExit = (err) => {
  for (const state of activeTurns.values()) {
    settleTurn(state, null, err);
  }
};

function createTurnState() {
  let resolve;
  let reject;
  const completion = new Promise((res, rej) => {
    resolve = res;
    reject = rej;
  });
  return { completion, resolve, reject, settled: false, lastAgentMessage: null, finalAnswer: null, error: null };
}

function settleTurn(state, turn, err) {
  if (state.settled) return;
  state.settled = true;
  if (err) {
    state.reject(err);
  } else {
    state.resolve(turn);
  }
}

async function runTurn(threadId, prompt, extra = {}) {
  const state = createTurnState();
  activeTurns.set(threadId, state);
  try {
    const response = await appServer.request("turn/start", {
      threadId,
      input: [{ type: "text", text: prompt }],
      ...extra
    });
    if (response.turn && response.turn.status && response.turn.status !== "inProgress") {
      settleTurn(state, response.turn);
    }

    const turn = await state.completion;
    const message = state.finalAnswer ?? state.lastAgentMessage;
    if (turn.status === "completed" && !turn.error && !state.error && message) {
      return { ok: true, threadId, content: message };
    }
    const reason = turn.error?.message ?? state.error?.message ?? (message ? null : "no agent message produced");
    return { ok: false, threadId, message: `Codex turn ${turn.status}: ${reason ?? "unknown error"} (threadId: ${threadId})` };
  } catch (err) {
    return { ok: false, threadId, message: `Codex turn failed: ${err.message} (threadId: ${threadId})` };
  } finally {
    activeTurns.delete(threadId);
  }
}

async function handleCodexTool(args) {
  if (!args.prompt) throw new Error("prompt is required");

  const params = {
    cwd: args.cwd ?? process.cwd(),
    approvalPolicy: args["approval-policy"] ?? "never",
    serviceName: "claude_code_codex_bridge"
  };
  if (args.model) params.model = args.model;
  if (args.sandbox) params.sandbox = args.sandbox;
  if (args["developer-instructions"]) params.developerInstructions = args["developer-instructions"];
  if (args["base-instructions"]) params.baseInstructions = args["base-instructions"];
  if (args.config) params.config = args.config;
  if (args["compact-prompt"]) {
    process.stderr.write("[codex-mcp-bridge] 'compact-prompt' has no codex app-server equivalent; ignoring.\n");
  }

  const response = await appServer.request("thread/start", params);
  const threadId = response.thread.id;
  knownThreads.add(threadId);
  return runTurn(threadId, args.prompt);
}

async function handleCodexReplyTool(args) {
  if (!args.prompt) throw new Error("prompt is required");
  const threadId = args.threadId ?? args.conversationId;
  if (!threadId) {
    return { ok: false, message: "threadId is required" };
  }

  if (!knownThreads.has(threadId)) {
    try {
      await appServer.request("thread/resume", { threadId, cwd: process.cwd() });
      knownThreads.add(threadId);
    } catch (err) {
      return { ok: false, threadId, message: `Failed to resume thread ${threadId}: ${err.message}` };
    }
  }

  return runTurn(threadId, args.prompt);
}

// --- Upstream: MCP stdio server talking to Claude Code ---
// Unlike app-server, MCP requires "jsonrpc":"2.0" on every message.

function sendMcp(obj) {
  process.stdout.write(JSON.stringify({ jsonrpc: "2.0", ...obj }) + "\n");
}

async function handleMcpMessage(msg) {
  const { id, method, params } = msg;

  if (method === "notifications/initialized") return;

  if (method === "initialize") {
    sendMcp({
      id,
      result: {
        protocolVersion: params?.protocolVersion ?? "2025-06-18",
        capabilities: { tools: {} },
        serverInfo: { name: "codex", version: "1.0.0" }
      }
    });
    return;
  }

  if (method === "ping") {
    sendMcp({ id, result: {} });
    return;
  }

  if (method === "tools/list") {
    sendMcp({ id, result: { tools: [CODEX_TOOL, CODEX_REPLY_TOOL] } });
    return;
  }

  if (method === "tools/call") {
    const name = params?.name;
    const args = params?.arguments ?? {};

    if (name !== "codex" && name !== "codex-reply") {
      sendMcp({ id, error: { code: -32601, message: `Unknown tool: ${name}` } });
      return;
    }

    let result;
    try {
      await appServer.ready.catch(() => {}); // surfaced via the request rejection below if it truly failed
      result = name === "codex" ? await handleCodexTool(args) : await handleCodexReplyTool(args);
    } catch (err) {
      result = { ok: false, message: err.message };
    }

    if (result.ok) {
      const structuredContent = { threadId: result.threadId, content: result.content };
      sendMcp({
        id,
        result: {
          structuredContent,
          content: [{ type: "text", text: JSON.stringify(structuredContent) }]
        }
      });
    } else {
      sendMcp({ id, result: { isError: true, content: [{ type: "text", text: result.message }] } });
    }
    return;
  }

  if (id !== undefined) {
    sendMcp({ id, error: { code: -32601, message: `Method not found: ${method}` } });
  }
}

const rlStdin = readline.createInterface({ input: process.stdin, crlfDelay: Infinity });

rlStdin.on("line", (line) => {
  if (!line.trim()) return;
  let msg;
  try {
    msg = JSON.parse(line);
  } catch {
    return; // no id to reply to
  }
  handleMcpMessage(msg).catch((err) => {
    if (msg.id !== undefined) {
      sendMcp({ id: msg.id, error: { code: -32603, message: err.message } });
    }
  });
});

rlStdin.on("close", () => {
  appServer.close();
  process.exit(0);
});

function shutdown() {
  appServer.close();
  process.exit(0);
}
process.on("SIGTERM", shutdown);
process.on("SIGINT", shutdown);

process.on("exit", () => {
  try {
    appServer.proc.kill("SIGKILL");
  } catch {}
});

process.on("unhandledRejection", (err) => {
  process.stderr.write(`[codex-mcp-bridge] unhandled rejection: ${err instanceof Error ? err.stack : err}\n`);
});
